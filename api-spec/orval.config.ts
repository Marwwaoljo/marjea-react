import { defineConfig, InputTransformerFn } from "orval";
import path from "path";

const root = path.resolve(__dirname, "..", "..");
const apiClientReactSrc = path.resolve(root, "lib", "api-client-react", "src");
const apiZodSrc = path.resolve(root, "lib", "api-zod", "src");

// Our exports make assumptions about the title of the API being "Api" (i.e. generated output is `api.ts`).
const titleTransformer: InputTransformerFn = (config) => {
  config.info ??= {};
  config.info.title = "Api";

  return config;
};

export default defineConfig({
  "api-client-react": {
    input: {
      target: "./openapi.yaml",
      parserOptions: { externalRefs: { allow: ["./phase2a.openapi.yaml", "./workspace.openapi.yaml"] } },
      override: {
        transformer: titleTransformer,
      },
    },
    output: {
      workspace: apiClientReactSrc,
      target: "generated",
      client: "react-query",
      mode: "split",
      baseUrl: "/api",
      clean: true,
      prettier: true,
      override: {
        fetch: {
          includeHttpResponseReturnType: false,
        },
        mutator: {
          path: path.resolve(apiClientReactSrc, "custom-fetch.ts"),
          name: "customFetch",
        },
      },
    },
  },
  zod: {
    input: {
      target: "./openapi.yaml",
      parserOptions: { externalRefs: { allow: ["./phase2a.openapi.yaml", "./workspace.openapi.yaml"] } },
      override: {
        transformer: titleTransformer,
      },
    },
    output: {
      workspace: apiZodSrc,
      client: "zod",
      target: "generated",
      schemas: { path: "generated/types", type: "typescript" },
      mode: "split",
      clean: true,
      prettier: true,
      override: {
        tags: {
          semantic: {
            zod: { strict: { body: true, response: true, query: true, param: true } },
          },
        },
        zod: {
          // Keep generated schemas aligned with the workspace Zod 4 catalog.
          version: 4,
          coerce: {
            // Query and path parameters are already strings in HTTP requests;
            // avoid wrapping UUID strings in ZodCoercedString, which has no
            // UUID validator in Zod 4.
            query: ['boolean', 'number'],
            param: ['boolean', 'number'],
            body: ['bigint', 'date'],
            response: ['bigint', 'date'],
          },
        },
        useDates: true,
        useBigInt: true,
      },
    },
  },
});
